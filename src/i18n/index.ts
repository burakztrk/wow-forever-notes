export type UiKey = keyof (typeof strings)['en'];
export type UiStrings = Record<UiKey, string>;

export function ui(lang: Lang): UiStrings {
  return strings[lang];
}

export function formatDate(date: Date, lang: Lang): string {
  return date.toLocaleDateString(lang === 'tr' ? 'tr-TR' : 'en-GB', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'Europe/Istanbul',
  });
}

// "16 Ekim" / "16 October": patch-note titles on class, race and profession pages
export function formatDayMonth(date: Date, lang: Lang): string {
  return date.toLocaleDateString(lang === 'tr' ? 'tr-TR' : 'en-GB', {
    month: 'long',
    day: 'numeric',
    timeZone: 'Europe/Istanbul',
  });
}
